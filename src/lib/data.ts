export function getServiceBySlug(slug: string): Service | undefined {
  if (!slug) return undefined;
  const normalized = slug.toLowerCase().trim();
  const direct = SERVICES.find((s) => s.slug === normalized);
  if (direct) return direct;
  const aliasMatch = SERVICES.find((s) => s.aliases?.includes(normalized));
  if (aliasMatch) return aliasMatch;
  const hyphenated = normalized.replace(/_/g, '-');
  return (
    SERVICES.find((s) => s.slug === hyphenated) ||
    SERVICES.find((s) => s.aliases?.some((a) => a.replace(/_/g, '-') === hyphenated))
  );
}

